import {
  type DrawingTemplate,
  type Pt,
  circle,
  scalePaths,
  smoothPath,
  svgPath,
} from "../engine/pathMath";

export type { DrawingTemplate };

/** Build one ink stroke from an SVG path string (viewBox 0..100). */
function ink(d: string, smooth = 1): Pt[] {
  const pts = svgPath(d, 100);
  return smooth > 0 ? smoothPath(pts, smooth) : pts;
}

function dot(x: number, y: number, r = 0.018): Pt[] {
  return circle(x / 100, y / 100, r, 16);
}

function T(
  id: string,
  title: string,
  emoji: string,
  category: string,
  color: string,
  paths: Pt[][],
): DrawingTemplate {
  return { id, title, emoji, category, color, paths: scalePaths(paths, 0.07) };
}

